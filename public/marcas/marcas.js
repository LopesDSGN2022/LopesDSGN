// const slug = location.pathname.split("/").filter(Boolean).pop()
const slug = new URLSearchParams(window.location.search).get("projeto") || "barnno"
const projeto = projetos[slug]

// fallback
if (!projeto) {
  document.getElementById("projectTitle").innerText = "Projeto não encontrado"
} else {

  document.getElementById("projectTitle").innerText = projeto.nome
  document.getElementById("projectCategory").innerText = projeto.categoria
  document.getElementById("projectDescription").innerText = projeto.descricao

  /* ===== CAROUSEL ===== */
  const carousel = document.getElementById("projectCarousel")
  carousel.innerHTML = ""

  projeto.banners.forEach((img, i) => {
    carousel.innerHTML += `
      <div class="carousel-item ${i === 0 ? "active" : ""}">
        <img src="${img}" class="d-block w-100">
      </div>
    `
  })

  /* ===== ARTES ===== */
  const artGallery = document.getElementById("artGallery")
  artGallery.innerHTML = ""

  projeto.artes.forEach(img => {
    artGallery.innerHTML += `
      <div class="col-6 col-md-4 col-lg-2-4">
        <div class="art-card" data-bs-toggle="modal" data-bs-target="#artModal" data-img="${img}">
          <img src="${img}">
        </div>
      </div>
    `
  })

  /* ===== APRESENTAÇÃO ===== */
  const presentationGallery = document.getElementById("presentationGallery")
  const presentationSection = document.getElementById("presentationSection")

  if (projeto.apresentacao && projeto.apresentacao.length > 0) {
    presentationGallery.innerHTML = ""

    projeto.apresentacao.forEach(img => {
      presentationGallery.innerHTML += `
        <div class="col-6 col-md-4 col-lg-2-4">
          <div class="art-card" data-bs-toggle="modal" data-bs-target="#artModal" data-img="${img}">
            <img src="${img}">
          </div>
        </div>
      `
    })
  } else {
    presentationSection.style.display = "none"
  }
}

